"""Tests-only Postgres schema and a Postgres-backed fake chat backend.

The chat service owns the real Alembic migrations. This DDL mirrors Deep Dive §4 (and the chat
service's 0001_initial_schema migration, column for column) for the tables
the agent reads and writes, so the agent can be tested against real Postgres before the chat
service lands. It is never used outside tests.
"""

