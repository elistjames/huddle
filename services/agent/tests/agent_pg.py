SCHEMA = """
CREATE TABLE users (
  id text PRIMARY KEY,
  display_name text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE chat_sessions (
  id text PRIMARY KEY,
  title text NOT NULL,
  status text NOT NULL CHECK (status IN ('active', 'closed')),
  last_seq bigint NOT NULL DEFAULT 0,
  last_human_message_at timestamptz,
  created_by text REFERENCES users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  closed_at timestamptz
);
CREATE TABLE agents (
  id text PRIMARY KEY,
  name text NOT NULL,
  avatar_url text NOT NULL DEFAULT '',
  model text NOT NULL,
  fallback_model text NOT NULL DEFAULT '',
  prompt_version text NOT NULL,
  config jsonb NOT NULL DEFAULT '{}',
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'paused', 'removed')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE session_memberships (
  session_id text NOT NULL REFERENCES chat_sessions(id),
  participant_id text NOT NULL,
  participant_type text NOT NULL CHECK (participant_type IN ('user', 'agent')),
  role text NOT NULL DEFAULT 'member' CHECK (role IN ('owner', 'member')),
  status text NOT NULL CHECK (status IN ('invited', 'active', 'left', 'removed')),
  last_delivered_seq bigint NOT NULL DEFAULT 0,
  last_read_seq bigint NOT NULL DEFAULT 0,
  preferences jsonb NOT NULL DEFAULT '{}',
  joined_at timestamptz NOT NULL DEFAULT now(),
  left_at timestamptz,
  PRIMARY KEY (session_id, participant_id)
);
CREATE INDEX session_memberships_participant ON session_memberships (participant_id);
CREATE TABLE agent_runs (
  id text PRIMARY KEY,
  session_id text NOT NULL REFERENCES chat_sessions(id),
  agent_id text NOT NULL REFERENCES agents(id),
  trigger_kind text NOT NULL CHECK (trigger_kind IN ('message', 'nudge')),
  trigger_seq bigint NOT NULL,
  context_seq bigint NOT NULL,
  status text NOT NULL CHECK (status IN (
    'triggered', 'eligible', 'skipped', 'context_built', 'generating', 'validated',
    'committed', 'observed', 'cancelled', 'superseded', 'timed_out', 'failed')),
  skip_reason text,
  error_code text,
  lease_owner text,
  lease_expires_at timestamptz,
  attempts int DEFAULT 0,
  prompt_version text,
  model text,
  input_tokens int,
  output_tokens int,
  latency_ms int,
  output_message_id text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX agent_runs_one_live ON agent_runs (session_id, agent_id)
  WHERE status IN ('eligible', 'context_built', 'generating', 'validated');
CREATE TABLE messages (
  id text PRIMARY KEY,
  session_id text NOT NULL REFERENCES chat_sessions(id),
  seq bigint NOT NULL,
  sender_type text NOT NULL CHECK (sender_type IN ('user', 'agent', 'system')),
  sender_id text NOT NULL,
  client_msg_id uuid NOT NULL,
  kind text NOT NULL CHECK (kind IN ('text', 'system')),
  body text CHECK (char_length(body) <= 4000),
  agent_run_id text REFERENCES agent_runs(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  redacted_at timestamptz,
  UNIQUE (session_id, seq),
  UNIQUE (session_id, sender_id, client_msg_id)
);
ALTER TABLE agent_runs ADD CONSTRAINT agent_runs_output_message
  FOREIGN KEY (output_message_id) REFERENCES messages(id);
CREATE TABLE session_summaries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id text NOT NULL REFERENCES chat_sessions(id),
  agent_id text NOT NULL REFERENCES agents(id),
  covers_through_seq bigint NOT NULL,
  summary text NOT NULL,
  token_count int NOT NULL,
  model text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX session_summaries_latest
  ON session_summaries (session_id, agent_id, created_at DESC);
"""

TABLES = (
    "session_summaries",
    "messages",
    "agent_runs",
    "session_memberships",
    "agents",
    "chat_sessions",
    "users",
)

SID = "ses_main"
AGENT_ID = "agt_main"
HUMANS = (("usr_alice", "Alice"), ("usr_bob", "Bob"))


def _with_db(dsn: str, db: str) -> str:
    parts = urlsplit(dsn)
    return urlunsplit(parts._replace(path="/" + db))


def _plain(dsn: str) -> str:
    return dsn.replace("postgresql+asyncpg://", "postgresql://")


async def _admin(base_dsn: str, statement: str) -> None:
    eng = create_async_engine(asyncpg_url(base_dsn), isolation_level="AUTOCOMMIT")
    try:
        async with eng.connect() as conn:
            await conn.execute(sa.text(statement))
    finally:
        await eng.dispose()


async def _create(base_dsn: str) -> str:
    name = f"huddle_agent_test_{uuid.uuid4().hex[:12]}"  # generated, never user input
    await _admin(base_dsn, f'CREATE DATABASE "{name}"')
    dsn = _with_db(_plain(base_dsn), name)
    eng = engine_for(dsn)
    try:
        async with eng.begin() as conn:
            for statement in SCHEMA.split(";"):
                if statement.strip():
                    await conn.execute(sa.text(statement))
    finally:
        await eng.dispose()
    return dsn


async def _drop(base_dsn: str, dsn: str) -> None:
    name = urlsplit(dsn).path.lstrip("/")
    await _admin(base_dsn, f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)')


def create_test_database(base_dsn: str) -> str:
    return asyncio.run(_create(base_dsn))


def drop_test_database(base_dsn: str, dsn: str) -> None:
    asyncio.run(_drop(base_dsn, dsn))


async def reset_and_seed(engine: AsyncEngine, agent_config: dict[str, Any] | None = None) -> None:
    import json

    async with engine.begin() as conn:
        await conn.execute(sa.text("TRUNCATE " + ", ".join(TABLES) + " CASCADE"))
        for uid, name in HUMANS:
            await conn.execute(
                sa.text("INSERT INTO users (id, display_name) VALUES (:i, :n)"),
                {"i": uid, "n": name},
            )
        await conn.execute(
            sa.text(
                "INSERT INTO chat_sessions (id, title, status) VALUES (:s, 'Huddle', 'active')"
            ),
            {"s": SID},
        )
        await conn.execute(
            sa.text(
                "INSERT INTO agents (id, name, model, fallback_model, prompt_version, config,"
                " status) VALUES (:a, 'Huddle AI', 'llama3.1:8b', '', 'v1', CAST(:c AS jsonb),"
                " 'active')"
            ),
            {"a": AGENT_ID, "c": json.dumps(agent_config or {})},
        )
        for pid, ptype in [*((u, "user") for u, _ in HUMANS), (AGENT_ID, "agent")]:
            await conn.execute(
                sa.text(
                    "INSERT INTO session_memberships (session_id, participant_id, participant_type,"
                    " status) VALUES (:s, :p, :t, 'active')"
                ),
                {"s": SID, "p": pid, "t": ptype},
            )


def engine_for(dsn: str) -> AsyncEngine:
    return create_async_engine(asyncpg_url(dsn))


@dataclass
class PgChatBackend:
    """Stand-in for the chat service over the real tables: gapless seq in the insert
    transaction, idempotent on (session, sender, client_msg_id), XADD after commit for human
    messages only (Deep Dive §2, §3)."""

    engine: AsyncEngine
    redis: Redis | None = None
    stream: str = "agent:triggers"
    capacity_tokens: int = fixed_window.DEFAULT_CAPACITY_TOKENS
    used_tokens: int = 0
    statuses: list[tuple[str, AgentState]] = field(default_factory=list[tuple[str, AgentState]])
    usage_log: list[tuple[str, int]] = field(default_factory=list[tuple[str, int]])

    async def submit(self, req: SubmitMessageRequest) -> SubmitMessageResponse:
        return await self.insert(
            req.session_id, req.sender.type.value, req.sender.id, req.body, req.client_msg_id
        )

    async def insert(
        self,
        session_id: str,
        sender_type: str,
        sender_id: str,
        body: str,
        client_msg_id: str | None = None,
        *,
        kind: str = "text",
        created_at: datetime | None = None,
        trigger: bool = True,
    ) -> SubmitMessageResponse:
        cmid = client_msg_id or str(uuid.uuid4())
        created = created_at or datetime.now(UTC)
        async with self.engine.begin() as conn:
            dup = (
                await conn.execute(
                    sa.text(
                        "SELECT id, seq FROM messages WHERE session_id = :s AND sender_id = :u"
                        " AND client_msg_id = CAST(:c AS uuid)"
                    ),
                    {"s": session_id, "u": sender_id, "c": cmid},
                )
            ).first()
            if dup is not None:
                return SubmitMessageResponse(message_id=dup[0], seq=dup[1], duplicate=True)
            status = (
                await conn.execute(
                    sa.text("SELECT status FROM chat_sessions WHERE id = :s FOR UPDATE"),
                    {"s": session_id},
                )
            ).scalar_one_or_none()
            if status != "active":
                raise ChatError(ErrorCode.SESSION_CLOSED.value, retryable=False, status=409)
            member = (
                await conn.execute(
                    sa.text(
                        "SELECT status FROM session_memberships WHERE session_id = :s"
                        " AND participant_id = :p"
                    ),
                    {"s": session_id, "p": sender_id},
                )
            ).scalar_one_or_none()
            if sender_type != "system" and member != "active":
                raise ChatError(ErrorCode.NOT_MEMBER.value, retryable=False, status=403)
            human = sender_type == "user" and kind == "text"
            seq = (
                await conn.execute(
                    sa.text(
                        "UPDATE chat_sessions SET last_seq = last_seq + 1, last_human_message_at ="
                        " CASE WHEN :human THEN :t ELSE last_human_message_at END"
                        " WHERE id = :s RETURNING last_seq"
                    ),
                    {"s": session_id, "t": created, "human": human},
                )
            ).scalar_one()
            run_link = None
            if sender_type == "agent":  # link the run only if its row exists (as chat does)
                run_link = (
                    await conn.execute(
                        sa.text("SELECT id FROM agent_runs WHERE id = :c"), {"c": cmid}
                    )
                ).scalar_one_or_none()
            mid = f"msg_{ULID()}"
            await conn.execute(
                sa.text(
                    "INSERT INTO messages (id, session_id, seq, sender_type, sender_id,"
                    " client_msg_id, kind, body, agent_run_id, created_at) VALUES (:id, :s, :q,"
                    " :st, :u, CAST(:c AS uuid), :k, :b, :run, :t)"
                ),
                {
                    "id": mid,
                    "s": session_id,
                    "q": seq,
                    "st": sender_type,
                    "u": sender_id,
                    "c": cmid,
                    "k": kind,
                    "b": body,
                    "run": run_link,
                    "t": created,
                },
            )
        if human and trigger and self.redis is not None:
            await self.redis.xadd(
                self.stream,
                {
                    "session_id": session_id,
                    "seq": str(seq),
                    "message_id": mid,
                    "sender_type": "user",
                },
            )
        return SubmitMessageResponse(message_id=mid, seq=int(seq))

    async def ack(self, req: AckDeliveryRequest) -> None:
        col = "last_read_seq" if req.kind == "read" else "last_delivered_seq"
        async with self.engine.begin() as conn:
            await conn.execute(
                sa.text(
                    f"UPDATE session_memberships SET {col} = GREATEST({col}, :q),"  # noqa: S608  # nosec B608 - fixed column names
                    " last_delivered_seq = GREATEST(last_delivered_seq, :q)"
                    " WHERE session_id = :s AND participant_id = :p"
                ),
                {"q": req.up_to_seq, "s": req.session_id, "p": req.participant_id},
            )

    async def status(self, session_id: str, state: AgentState) -> None:
        self.statuses.append((session_id, state))

    async def usage(self, session_id: str, req: RecordUsageRequest) -> None:
        self.used_tokens += req.tokens
        self.usage_log.append((req.run_id, req.tokens))

    async def budget(self, session_id: str) -> BudgetState:
        now = datetime.now(UTC)
        refills = fixed_window.window_end(now, fixed_window.DEFAULT_WINDOW_SECONDS)
        return BudgetState(
            capacity_tokens=self.capacity_tokens,
            used_tokens=self.used_tokens,
            window_seconds=fixed_window.DEFAULT_WINDOW_SECONDS,
            window_started_at=fixed_window.window_start(now, fixed_window.DEFAULT_WINDOW_SECONDS),
            refills_at=refills,
            view=BudgetView(
                used_pct=fixed_window.used_pct(self.used_tokens, self.capacity_tokens),
                refills_at=refills,
            ),
        )

    async def member(self, session_id: str, participant_id: str) -> MembershipCheck:
        async with self.engine.connect() as conn:
            row = (
                await conn.execute(
                    sa.text(
                        "SELECT m.status, m.participant_type, m.last_delivered_seq,"
                        " COALESCE(u.display_name, a.name) FROM session_memberships m"
                        " LEFT JOIN users u ON u.id = m.participant_id"
                        " LEFT JOIN agents a ON a.id = m.participant_id"
                        " WHERE m.session_id = :s AND m.participant_id = :p"
                    ),
                    {"s": session_id, "p": participant_id},
                )
            ).first()
        if row is None:
            return MembershipCheck(is_active=False)
        return MembershipCheck(
            is_active=row[0] == "active",
            participant_type=row[1],
            last_delivered_seq=int(row[2]),
            display_name=row[3],
        )

    async def agent_cursor(self) -> int:
        async with self.engine.connect() as conn:
            return int(
                (
                    await conn.execute(
                        sa.text(
                            "SELECT last_read_seq FROM session_memberships WHERE session_id = :s"
                            " AND participant_id = :p"
                        ),
                        {"s": SID, "p": AGENT_ID},
                    )
                ).scalar_one()
            )

    async def agent_bodies(self) -> list[str]:
        async with self.engine.connect() as conn:
            rows = await conn.execute(
                sa.text(
                    "SELECT body FROM messages WHERE session_id = :s AND sender_type = 'agent'"
                    " ORDER BY seq"
                ),
                {"s": SID},
            )
            return [str(r[0]) for r in rows]

    async def runs(self) -> list[dict[str, Any]]:
        async with self.engine.connect() as conn:
            rows = await conn.execute(
                sa.text("SELECT * FROM agent_runs ORDER BY lease_expires_at NULLS FIRST")
            )
            return [dict(r._mapping) for r in rows]  # pyright: ignore[reportPrivateUsage]
